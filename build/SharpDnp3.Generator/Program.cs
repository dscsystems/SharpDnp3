// Reads Objects/Spec/dnp3_objects.yaml and emits the object codecs, the
// descriptor registry, and the size table the framing layer needs.
//
// It exists because the group/variation matrix is a few hundred near-identical
// encodings. Hand-writing them produces hundreds of files that differ by a
// field width, and every Level 4 addition means touching all of them. One
// declarative table and a generator means adding a variation is one line.
//
// The output is committed, so consumers never run the generator, and CI fails
// if the committed files drift from the spec.

using System.Globalization;
using System.Text;
using SharpDnp3.Generator;

var specPath = "src/SharpDnp3/Objects/Spec/dnp3_objects.yaml";
var root = ".";
var checkOnly = false;

for (var i = 0; i < args.Length; i++)
{
    switch (args[i])
    {
        case "-spec" when i + 1 < args.Length:
            specPath = args[++i];
            break;
        case "-root" when i + 1 < args.Length:
            root = args[++i];
            break;
        case "-check":
            checkOnly = true;
            break;
        default:
            Console.Error.WriteLine($"gen: unknown argument {args[i]}");
            return 2;
    }
}

try
{
    var spec = SpecLoader.Load(Path.Combine(root, specPath));

    (string Path, Func<Spec, string> Emit)[] outputs =
    [
        (Path.Combine(root, "src/SharpDnp3/Objects/Generated.Descriptors.cs"), Emitters.EmitDescriptors),
        (Path.Combine(root, "src/SharpDnp3/Objects/Generated.Codecs.cs"), Emitters.EmitCodecs),
        (Path.Combine(root, "src/SharpDnp3/App/Generated.Sizes.cs"), Emitters.EmitSizes),
    ];

    var drifted = false;
    foreach (var (path, emit) in outputs)
    {
        var source = emit(spec);

        if (checkOnly)
        {
            var existing = File.Exists(path) ? File.ReadAllText(path) : null;
            if (existing != source)
            {
                Console.Error.WriteLine($"gen: {path} has drifted from the spec");
                drifted = true;
            }

            continue;
        }

        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllText(path, source);
        Console.WriteLine(string.Format(
            CultureInfo.InvariantCulture,
            "gen: wrote {0} ({1} objects)", path, spec.Objects.Count));
    }

    if (checkOnly)
    {
        if (drifted)
        {
            return 1;
        }

        Console.WriteLine("gen: generated files match the spec");
    }

    return 0;
}
catch (Exception ex) when (ex is InvalidOperationException or IOException)
{
    Console.Error.WriteLine($"gen: {ex.Message}");
    return 1;
}

namespace SharpDnp3.Generator
{
    /// <summary>Emits the three generated C# files from the spec.</summary>
    public static class Emitters
    {
        private const string Header =
            "// <auto-generated>\n" +
            "// Code generated by build/SharpDnp3.Generator from\n" +
            "// src/SharpDnp3/Objects/Spec/dnp3_objects.yaml. DO NOT EDIT.\n" +
            "// </auto-generated>\n" +
            "//\n" +
            "// SharpDnp3 — a DNP3 (IEEE 1815-2012) implementation in C#.\n" +
            "// Copyright (C) 2026 Ricardo Olsen / DSC Systems\n" +
            "// Licensed under the GNU General Public License v3.0 or later.\n\n";

        // ------------------------------------------------------ descriptors

        public static string EmitDescriptors(Spec s)
        {
            var b = new StringBuilder(Header);
            b.Append("namespace SharpDnp3.Objects;\n\n");
            b.Append("public static partial class ObjectRegistry\n{\n");

            b.Append("    /// <summary>Every group and variation the spec defines.</summary>\n");
            b.Append("    private static readonly Dictionary<GroupVar, Descriptor> Descriptors = new()\n    {\n");

            foreach (var o in s.Objects)
            {
                if (o.Variable || o.LengthIsVariation)
                {
                    continue; // these are rules, not rows; see SizeBits
                }

                var (bits, _) = o.SizeBits();
                var hasFlags = o.FlagsField() is not null;
                var hasAbs = o.AbsTimeField() is not null;
                var hasRel = o.RelTimeField() is not null;

                b.Append(Inv("        [GroupVar.GV({0}, {1})] = new Descriptor\n", o.Group, o.Variation));
                b.Append("        {\n");
                b.Append(Inv("            GV = GroupVar.GV({0}, {1}),\n", o.Group, o.Variation));
                b.Append(Inv("            Name = \"{0}\",\n", o.Name));
                b.Append(Inv("            Level = {0},\n", o.Level));
                b.Append(Inv("            Kind = {0},\n", SpecTables.ValidKinds[o.Kind]));
                b.Append(Inv("            Measurement = {0},\n", PointTypeConst(o.Measurement)));
                b.Append(Inv("            SizeBits = {0},\n", bits));

                if (o.Packed > 0)
                {
                    b.Append("            Packed = true,\n");
                }

                if (hasFlags)
                {
                    b.Append("            HasFlags = true,\n");
                }

                if (hasAbs || hasRel)
                {
                    b.Append("            HasTime = true,\n");
                }

                if (hasRel)
                {
                    b.Append("            RelativeTime = true,\n");
                }

                if (o.ValueField() is { } vf)
                {
                    b.Append(Inv("            ValueBits = {0},\n", SpecTables.FieldBits[vf.Field.Type]));
                    if (vf.Field.Type is "f32" or "f64")
                    {
                        b.Append("            FloatValue = true,\n");
                    }
                }

                b.Append("        },\n");
            }

            b.Append("    };\n\n");

            b.Append("    /// <summary>\n");
            b.Append("    /// Groups that carry their octet length in the variation number, so a\n");
            b.Append("    /// range of them needs no size table entry.\n");
            b.Append("    /// </summary>\n");
            b.Append("    private static readonly HashSet<byte> LengthIsVariationGroups =\n    [\n");
            foreach (var o in s.Objects)
            {
                if (o.LengthIsVariation)
                {
                    b.Append(Inv("        {0}, // {1}\n", o.Group, o.Name));
                }
            }

            b.Append("    ];\n\n");

            b.Append("    /// <summary>\n");
            b.Append("    /// Groups that are genuinely variable-length. Their encodings carry an\n");
            b.Append("    /// explicit size, so a parser walks them instead of looking them up.\n");
            b.Append("    /// </summary>\n");
            b.Append("    private static readonly HashSet<byte> VariableGroups =\n    [\n");
            foreach (var o in s.Objects)
            {
                if (o.Variable)
                {
                    b.Append(Inv("        {0}, // {1}\n", o.Group, o.Name));
                }
            }

            b.Append("    ];\n");
            b.Append("}\n");
            return b.ToString();
        }

        private static string PointTypeConst(string measure)
        {
            var name = SpecTables.ValidMeasurements[measure];
            return name.Length == 0 ? "PointType.Unknown" : "PointType." + name;
        }

        // ------------------------------------------------------------ sizes

        public static string EmitSizes(Spec s)
        {
            var b = new StringBuilder(Header);
            b.Append("namespace SharpDnp3.App;\n\n");
            b.Append("internal static partial class ObjectSizing\n{\n");

            b.Append("    /// <summary>\n");
            b.Append("    /// Maps a group and variation to the encoded size of one object in bits.\n");
            b.Append("    /// Sizes under eight bits are bit-packed across a range.\n");
            b.Append("    /// </summary>\n");
            b.Append("    private static readonly Dictionary<ushort, int> GeneratedSizes = new()\n    {\n");

            foreach (var o in s.Objects)
            {
                if (o.Variable || o.LengthIsVariation)
                {
                    continue;
                }

                var (bits, _) = o.SizeBits();
                b.Append(Inv("        [Gv({0}, {1})] = {2}, // {3}\n", o.Group, o.Variation, bits, o.Name));
            }

            b.Append("    };\n\n");

            b.Append("    /// <summary>\n");
            b.Append("    /// Groups that carry their octet length in the variation number.\n");
            b.Append("    /// </summary>\n");
            b.Append("    private static readonly HashSet<byte> LengthIsVariationGroups =\n    [\n");
            foreach (var o in s.Objects)
            {
                if (o.LengthIsVariation)
                {
                    b.Append(Inv("        {0}, // {1}\n", o.Group, o.Name));
                }
            }

            b.Append("    ];\n\n");

            b.Append("    /// <summary>\n");
            b.Append("    /// Groups with no fixed size; their encoding carries one.\n");
            b.Append("    /// </summary>\n");
            b.Append("    private static readonly HashSet<byte> VariableGroups =\n    [\n");
            foreach (var o in s.Objects)
            {
                if (o.Variable)
                {
                    b.Append(Inv("        {0}, // {1}\n", o.Group, o.Name));
                }
            }

            b.Append("    ];\n");
            b.Append("}\n");
            return b.ToString();
        }

        // ----------------------------------------------------------- codecs

        public static string EmitCodecs(Spec s)
        {
            var b = new StringBuilder(Header);
            b.Append("using System.Buffers.Binary;\n\n");
            b.Append("namespace SharpDnp3.Objects;\n\n");
            b.Append("public static partial class ObjectRegistry\n{\n");

            var byMeasure = new Dictionary<string, List<ObjectSpec>>();
            foreach (var o in s.Objects)
            {
                if (!o.IsMeasurement())
                {
                    continue;
                }

                if (!byMeasure.TryGetValue(o.Measurement, out var list))
                {
                    byMeasure[o.Measurement] = list = [];
                }

                list.Add(o);
            }

            foreach (var m in SpecTables.MeasurementOrder)
            {
                if (!byMeasure.TryGetValue(m, out var objs) || objs.Count == 0)
                {
                    continue;
                }

                var csType = SpecTables.ValidMeasurements[m];

                b.Append(Inv("    // ---- {0} ----\n\n", csType));
                foreach (var o in objs)
                {
                    EmitParse(b, o, csType);
                    EmitWrite(b, o, csType);
                }

                b.Append(Inv(
                    "    private static readonly Dictionary<GroupVar, Codec<{0}>> {1} = new()\n    {{\n",
                    csType, SpecTables.CodecMapName(m)));

                foreach (var o in objs)
                {
                    b.Append(Inv(
                        "        [GroupVar.GV({0}, {1})] = new Codec<{2}>(Parse{3}, Write{3}),\n",
                        o.Group, o.Variation, csType, o.CsName()));
                }

                b.Append("    };\n\n");
            }

            // Trim the trailing blank line before the closing brace.
            while (b.Length > 0 && b[^1] == '\n' && b.Length > 1 && b[^2] == '\n')
            {
                b.Length--;
            }

            b.Append("}\n");
            return b.ToString();
        }

        /// <summary>Writes the decoder for one variation.</summary>
        private static void EmitParse(StringBuilder b, ObjectSpec o, string csType)
        {
            b.Append(Inv(
                "    /// <summary>Decodes g{0}v{1}, {2}.</summary>\n", o.Group, o.Variation, o.Name));
            b.Append(Inv(
                "    private static {0} Parse{1}(ReadOnlySpan<byte> buf, Context ctx)\n    {{\n",
                csType, o.CsName()));

            // Flags, and the state the binary measurements carry inside them.
            var valueExpr = DefaultValueExpr(o.Measurement);
            if (o.FlagsField() is { } flagsField)
            {
                var off = o.OffsetOf(flagsField.Name);
                b.Append(Inv("        var flags = new Flags(buf[{0}]);\n", off));
                valueExpr = o.Measurement switch
                {
                    "binary" or "binaryoutput" =>
                        Inv("(buf[{0}] & 0x80) != 0", off),
                    "doublebit" =>
                        Inv("(DoubleBit)(buf[{0}] >> 6)", off),
                    _ => valueExpr,
                };
            }
            else
            {
                // A no-flag variation carries no quality information at all.
                // Reporting it as online matches what every other
                // implementation does and is the only reading that lets the
                // value be used; the alternative would mark perfectly good data
                // as offline.
                b.Append("        var flags = Flags.Online;\n");
            }

            // Numeric value.
            if (o.ValueField() is { } vf)
            {
                valueExpr = ReadExpr(vf.Field.Type, vf.Offset, o.Measurement);
            }

            // Time.
            if (o.AbsTimeField() is { } absField)
            {
                var off = o.OffsetOf(absField.Name);
                b.Append("        var time = new Timestamp\n        {\n");
                b.Append(Inv(
                    "            Time = Dnp3Time.FromDnp3(ObjectConvert.ReadTime48(buf.Slice({0}, 6))),\n",
                    off));
                b.Append("            Quality = ctx.TimeQuality(),\n");
                b.Append("        };\n");
            }
            else if (o.RelTimeField() is { } relField)
            {
                var off = o.OffsetOf(relField.Name);
                b.Append("        // A relative-time event is an offset from the common time of\n");
                b.Append("        // occurrence in a preceding group 51 object. Without one the\n");
                b.Append("        // offset is meaningless, so the timestamp is left invalid\n");
                b.Append("        // rather than being anchored to the epoch.\n");
                b.Append(Inv(
                    "        var time = ctx.RelativeTime(BinaryPrimitives.ReadUInt16LittleEndian(buf.Slice({0}, 2)));\n",
                    off));
            }
            else
            {
                b.Append("        var time = Timestamp.NoTime();\n");
            }

            b.Append(Inv("        return new {0}({1}, flags, time);\n", csType, valueExpr));
            b.Append("    }\n\n");
        }

        /// <summary>Writes the encoder for one variation.</summary>
        private static void EmitWrite(StringBuilder b, ObjectSpec o, string csType)
        {
            b.Append(Inv(
                "    /// <summary>Encodes g{0}v{1}, {2}.</summary>\n", o.Group, o.Variation, o.Name));
            b.Append(Inv(
                "    private static void Write{0}(List<byte> dst, {1} v, Context ctx)\n    {{\n",
                o.CsName(), csType));

            foreach (var f in o.Fields)
            {
                switch (f.Type)
                {
                    case "flags":
                        switch (o.Measurement)
                        {
                            case "binary":
                            case "binaryoutput":
                                b.Append("        var flags = v.Flags.Clear(Flags.StateBit);\n");
                                b.Append("        if (v.Value)\n        {\n");
                                b.Append("            flags = flags.Set(Flags.StateBit);\n");
                                b.Append("        }\n\n");
                                b.Append("        dst.Add(flags.Value);\n");
                                break;

                            case "doublebit":
                                b.Append("        dst.Add((byte)((v.Flags.Value & 0x3F) | (((int)v.Value & 0x03) << 6)));\n");
                                break;

                            default:
                                b.Append("        dst.Add(v.Flags.Value);\n");
                                break;
                        }

                        break;

                    case "time48":
                        b.Append("        ObjectConvert.AppendTime48(dst, Dnp3Time.ToDnp3(v.Time.Time));\n");
                        break;

                    case "time16":
                        // A relative-time event encodes an offset from the
                        // context's common time of occurrence, so the writer
                        // needs the same context the reader does.
                        b.Append("        ObjectConvert.AppendUInt16(dst, ctx.RelativeOffset(v.Time));\n");
                        break;

                    default:
                        if (f.Name == "Value")
                        {
                            b.Append("        " + WriteExpr(f.Type, o.Measurement) + "\n");
                        }

                        break;
                }
            }

            // Not every variation reads its context; say so rather than let an
            // analyzer flag the parameter.
            if (o.RelTimeField() is null)
            {
                b.Append("\n        _ = ctx;\n");
            }

            b.Append("    }\n\n");
        }

        private static string DefaultValueExpr(string measure) => measure switch
        {
            "binary" or "binaryoutput" => "false",
            "doublebit" => "DoubleBit.Intermediate",
            "counter" or "frozencounter" => "0u",
            _ => "0d",
        };

        /// <summary>
        /// Builds the expression that decodes a numeric value field into the
        /// measurement's C# type.
        /// </summary>
        private static string ReadExpr(string type, int off, string measure)
        {
            var toFloat = measure is "analog" or "analogoutput";

            return type switch
            {
                "i16" => Cast(
                    Inv("BinaryPrimitives.ReadInt16LittleEndian(buf.Slice({0}, 2))", off),
                    toFloat ? "double" : "uint"),
                "u16" => Cast(
                    Inv("BinaryPrimitives.ReadUInt16LittleEndian(buf.Slice({0}, 2))", off),
                    toFloat ? "double" : "uint"),
                "i32" => Cast(
                    Inv("BinaryPrimitives.ReadInt32LittleEndian(buf.Slice({0}, 4))", off),
                    toFloat ? "double" : "uint"),
                "u32" => toFloat
                    ? Cast(Inv("BinaryPrimitives.ReadUInt32LittleEndian(buf.Slice({0}, 4))", off), "double")
                    : Inv("BinaryPrimitives.ReadUInt32LittleEndian(buf.Slice({0}, 4))", off),
                "f32" => Cast(
                    Inv("BinaryPrimitives.ReadSingleLittleEndian(buf.Slice({0}, 4))", off), "double"),
                "f64" => Inv("BinaryPrimitives.ReadDoubleLittleEndian(buf.Slice({0}, 8))", off),
                _ => "0",
            };
        }

        private static string Cast(string expr, string type) => $"({type}){expr}";

        /// <summary>Builds the statement that encodes a value field.</summary>
        /// <remarks>
        /// Narrowing conversions go through the clamp helpers rather than a
        /// bare cast: converting an out-of-range double to an integer is
        /// unchecked in C#, and an analog reading that drifts past a 16-bit
        /// point's range would otherwise encode as an arbitrary value instead
        /// of a saturated one.
        /// </remarks>
        private static string WriteExpr(string type, string measure)
        {
            var fromFloat = measure is "analog" or "analogoutput";

            return type switch
            {
                "i16" => fromFloat
                    ? "ObjectConvert.AppendInt16(dst, ObjectConvert.ClampInt16(v.Value));"
                    : "ObjectConvert.AppendInt16(dst, (short)v.Value);",
                "u16" => fromFloat
                    ? "ObjectConvert.AppendUInt16(dst, ObjectConvert.ClampUInt16(v.Value));"
                    : "ObjectConvert.AppendUInt16(dst, (ushort)v.Value);",
                "i32" => fromFloat
                    ? "ObjectConvert.AppendInt32(dst, ObjectConvert.ClampInt32(v.Value));"
                    : "ObjectConvert.AppendInt32(dst, (int)v.Value);",
                "u32" => fromFloat
                    ? "ObjectConvert.AppendUInt32(dst, ObjectConvert.ClampUInt32(v.Value));"
                    : "ObjectConvert.AppendUInt32(dst, (uint)v.Value);",
                "f32" => "ObjectConvert.AppendSingle(dst, (float)v.Value);",
                "f64" => "ObjectConvert.AppendDouble(dst, v.Value);",
                _ => "",
            };
        }

        private static string Inv(string format, params object[] args) =>
            string.Format(CultureInfo.InvariantCulture, format, args);
    }
